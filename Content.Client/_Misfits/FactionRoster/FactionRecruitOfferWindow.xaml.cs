using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Misfits.FactionRoster;

[GenerateTypedNameReferences]
public sealed partial class FactionRecruitOfferWindow : FancyWindow
{
    public event Action? OnAccepted;
    public event Action? OnDeclined;

    public FactionRecruitOfferWindow()
    {
        RobustXamlLoader.Load(this);
        AcceptButton.OnPressed += _ => OnAccepted?.Invoke();
        DeclineButton.OnPressed += _ => OnDeclined?.Invoke();
    }

    public void SetOffer(string factionName, string recruiterName, string offerText)
    {
        HeaderLabel.Text = Loc.GetString("faction-recruit-offer-header",
            ("faction", factionName), ("recruiter", recruiterName));
        // Leadership writes the oath, so render it as plain text (no markup).
        OfferText.SetMessage(FormattedMessage.FromUnformatted(offerText));
    }
}
