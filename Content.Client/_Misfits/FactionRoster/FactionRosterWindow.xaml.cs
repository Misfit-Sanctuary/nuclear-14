using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Roles;
using Content.Shared._Misfits.FactionRoster;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Misfits.FactionRoster;

[GenerateTypedNameReferences]
public sealed partial class FactionRosterWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    /// <summary>Keep in sync with FactionRosterSystem.MaxOathLength.</summary>
    private const int MaxOathLength = 8000;

    private const int OathTab = 2;

    private static readonly Color OnlineColor = Color.FromHex("#7fc96b");
    private static readonly Color OfflineColor = Color.FromHex("#8a8a8a");
    private static readonly Color LeadershipColor = Color.FromHex("#d6b85a");

    public event Action? OnRefresh;
    public event Action<NetUserId, int>? OnPromote;
    public event Action<NetUserId, int>? OnDemote;
    public event Action<NetUserId>? OnDischarge;
    public event Action<NetUserId, string>? OnToggleSpecialty;
    public event Action<NetEntity>? OnRecruit;
    public event Action<string?>? OnSetOath;

    private FactionRosterEuiState? _state;

    /// <summary>Oath last received from the server, to avoid clobbering unsaved edits.</summary>
    private string? _serverOath;

    public FactionRosterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("faction-roster-tab-roster"));
        Tabs.SetTabTitle(1, Loc.GetString("faction-roster-tab-recruit"));
        Tabs.SetTabTitle(OathTab, Loc.GetString("faction-roster-tab-oath"));
        Tabs.SetTabVisible(OathTab, false);

        OathHint.Text = Loc.GetString("faction-roster-oath-hint");

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        FilterBox.OnTextChanged += _ => RebuildMembers();
        OathEdit.OnTextChanged += _ => UpdateOathCounter();
        OathSaveButton.OnPressed += _ => OnSetOath?.Invoke(Rope.Collapse(OathEdit.TextRope));
        OathResetButton.OnPressed += _ => OnSetOath?.Invoke(null);
    }

    public void UpdateState(FactionRosterEuiState state)
    {
        _state = state;
        Title = state.Title;

        SummaryLabel.Text = state.Loading
            ? Loc.GetString("faction-roster-loading")
            : Loc.GetString("faction-roster-summary",
                ("total", state.Members.Count),
                ("online", state.Members.Count(m => m.Online)));

        StatusLabel.Text = state.Status ?? string.Empty;
        StatusLabel.Visible = !string.IsNullOrEmpty(state.Status);

        RebuildMembers();
        RebuildCandidates();
        UpdateOath(state);
    }

    private string JobName(string id)
    {
        return _proto.TryIndex<JobPrototype>(id, out var job) ? job.LocalizedName : id;
    }

    #region Roster

    /// <summary>Rank text: the member's command role (e.g. DAGGER), or their rank on each track.</summary>
    private string RankText(FactionRosterEuiState state, FactionRosterMember member)
    {
        if (member.Command && member.CommandRoles.Count > 0)
            return string.Join(" / ", member.CommandRoles.Select(JobName));

        var ranks = new List<string>();
        for (var t = 0; t < state.Tracks.Count && t < member.Standings.Count; t++)
        {
            var rank = member.Standings[t].Rank;
            if (rank >= 0)
                ranks.Add(JobName(state.Tracks[t].Ranks[rank]));
        }

        return string.Join(" / ", ranks);
    }

    private int SortKey(FactionRosterMember member)
    {
        return member.Command ? 1000 : member.Standings.Count == 0 ? -1 : member.Standings.Max(s => s.Rank);
    }

    private void RebuildMembers()
    {
        MemberList.RemoveAllChildren();
        if (_state is not { } state)
            return;

        var filter = FilterBox.Text.Trim();
        var members = state.Members
            .Where(m => filter.Length == 0
                        || m.UserName.Contains(filter, StringComparison.OrdinalIgnoreCase)
                        || (m.CharacterName?.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false))
            .OrderByDescending(SortKey)
            .ThenByDescending(m => m.Online)
            .ThenBy(m => m.CharacterName ?? m.UserName)
            .ToList();

        if (members.Count == 0)
        {
            MemberList.AddChild(new Label
            {
                Text = Loc.GetString(state.Loading ? "faction-roster-loading" : "faction-roster-empty"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        foreach (var member in members)
            MemberList.AddChild(BuildMemberRow(state, member));
    }

    private Control BuildMemberRow(FactionRosterEuiState state, FactionRosterMember member)
    {
        var panel = new PanelContainer { StyleClasses = { "BackgroundDark" } };
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(6, 4),
        };
        panel.AddChild(row);

        // Name + status.
        var info = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        info.AddChild(new Label
        {
            Text = member.CharacterName ?? member.UserName,
            ToolTip = member.UserName,
            FontColorOverride = member.Command ? LeadershipColor : null,
        });
        info.AddChild(new Label
        {
            Text = Loc.GetString(!member.Online
                ? "faction-roster-offline"
                : member.CharacterName == null
                    ? "faction-roster-online"
                    : "faction-roster-on-duty"),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = member.Online ? OnlineColor : OfflineColor,
        });
        row.AddChild(info);

        // Rank, plus side roles for non-leadership members.
        var ranks = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            MinWidth = 190,
        };
        ranks.AddChild(new Label { Text = RankText(state, member) });
        if (!member.Command && member.Specialties.Count > 0)
        {
            ranks.AddChild(new Label
            {
                Text = string.Join(", ", member.Specialties.Select(JobName)),
                StyleClasses = { "LabelSubText" },
            });
        }
        row.AddChild(ranks);

        if (member.Locked)
            return panel;

        var multiTrack = state.Tracks.Count > 1;
        for (var t = 0; t < state.Tracks.Count && t < member.Standings.Count; t++)
            row.AddChild(BuildTrackButtons(state.Tracks[t], member, member.Standings[t], t, multiTrack));

        foreach (var specialty in state.Specialties)
        {
            var held = member.Specialties.Contains(specialty);
            var toggle = new Button
            {
                Text = JobName(specialty),
                ToggleMode = true,
                Pressed = held,
                VerticalAlignment = VAlignment.Center,
                ToolTip = Loc.GetString(held ? "faction-roster-specialty-revoke" : "faction-roster-specialty-grant",
                    ("role", JobName(specialty))),
            };
            toggle.OnPressed += _ => OnToggleSpecialty?.Invoke(member.UserId, specialty);
            row.AddChild(toggle);
        }

        // #Cythisiax Added - only those allowed to discharge see the button
        if (!state.CanDischarge)
            return panel;

        var discharge = new ConfirmButton
        {
            Text = Loc.GetString("faction-roster-discharge"),
            ConfirmationText = Loc.GetString("faction-roster-discharge-confirm"),
            StyleClasses = { "Caution" },
            VerticalAlignment = VAlignment.Center,
        };
        discharge.OnPressed += _ => OnDischarge?.Invoke(member.UserId);
        row.AddChild(discharge);

        return panel;
    }

    /// <summary>
    /// Promote / demote for one track. A single-track roster gets plain "Promote" / "Demote";
    /// with several tracks each pair is labelled with the track name.
    /// </summary>
    private Control BuildTrackButtons(
        FactionRosterTrackInfo track,
        FactionRosterMember member,
        FactionRosterStanding standing,
        int index,
        bool multiTrack)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 2,
            VerticalAlignment = VAlignment.Center,
        };

        if (multiTrack)
        {
            box.AddChild(new Label
            {
                Text = track.Name,
                StyleClasses = { "LabelSubText" },
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 2, 0),
            });
        }

        var promote = new Button
        {
            Text = multiTrack ? "▲" : Loc.GetString("faction-roster-promote"),
            Disabled = !standing.CanPromote,
        };
        if (standing.Rank + 1 < track.Ranks.Count)
            promote.ToolTip = Loc.GetString("faction-roster-promote-tooltip", ("rank", JobName(track.Ranks[standing.Rank + 1])));
        promote.OnPressed += _ => OnPromote?.Invoke(member.UserId, index);
        box.AddChild(promote);

        var demote = new Button
        {
            Text = multiTrack ? "▼" : Loc.GetString("faction-roster-demote"),
            Disabled = !standing.CanDemote,
        };
        if (standing.Rank > 0)
            demote.ToolTip = Loc.GetString("faction-roster-demote-tooltip", ("rank", JobName(track.Ranks[standing.Rank - 1])));
        else if (standing.Rank == 0)
            demote.ToolTip = Loc.GetString("faction-roster-demote-remove-tooltip", ("rank", JobName(track.Ranks[0])));
        demote.OnPressed += _ => OnDemote?.Invoke(member.UserId, index);
        box.AddChild(demote);

        return box;
    }

    #endregion

    #region Recruit

    private void RebuildCandidates()
    {
        CandidateList.RemoveAllChildren();
        if (_state is not { } state)
            return;

        if (state.Candidates.Count == 0)
        {
            CandidateList.AddChild(new Label
            {
                Text = Loc.GetString("faction-roster-recruit-none"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        foreach (var candidate in state.Candidates)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                Margin = new Thickness(6, 2),
            };
            row.AddChild(new Label
            {
                Text = candidate.Name,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });

            var recruit = new Button
            {
                Text = Loc.GetString(candidate.Pending ? "faction-roster-recruit-pending" : "faction-roster-recruit"),
                Disabled = candidate.Pending,
                MinWidth = 120,
            };
            recruit.OnPressed += _ => OnRecruit?.Invoke(candidate.Entity);
            row.AddChild(recruit);

            CandidateList.AddChild(row);
        }
    }

    #endregion

    #region Oath

    private void UpdateOath(FactionRosterEuiState state)
    {
        Tabs.SetTabVisible(OathTab, state.CanEditOath);
        OathResetButton.Disabled = !state.OathIsCustom;

        // Only overwrite the editor when the server's oath actually changed, so a
        // roster refresh doesn't wipe what leadership is typing.
        if (_serverOath != state.Oath)
        {
            _serverOath = state.Oath;
            OathEdit.TextRope = new Rope.Leaf(state.Oath);
        }

        UpdateOathCounter();
    }

    private void UpdateOathCounter()
    {
        var length = Rope.Collapse(OathEdit.TextRope).Length;
        OathCounter.Text = Loc.GetString("faction-roster-oath-counter", ("count", length), ("max", MaxOathLength));
        OathCounter.FontColorOverride = length > MaxOathLength ? Color.FromHex("#d65a4a") : null;
        OathSaveButton.Disabled = length > MaxOathLength;
    }

    #endregion
}
