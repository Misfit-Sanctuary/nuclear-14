// #Misfits Add - Admin tab for the event pool: run/roll events and tune the scheduler.
using System.Linq;
using Content.Client._Misfits.Events;
using Content.Shared._Misfits.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Misfits.Administration.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class MisfitsEventsTab : Control
{
    private MisfitsEventsClientSystem _events = default!;

    // Guards checkbox handlers while the tab is being refreshed from a snapshot.
    private bool _updating;

    public MisfitsEventsTab()
    {
        RobustXamlLoader.Load(this);
        _events = IoCManager.Resolve<IEntityManager>().System<MisfitsEventsClientSystem>();

        CvarCheck.Text = "Automatic events (misfits.events_enabled)";
        AutoCheck.Text = "Scheduler enabled this round";
        StatusLabel.Text = "Waiting for event state...";
        ResultLabel.Text = string.Empty;

        RollButton.OnPressed += _ => Send(new MisfitsEventAdminActionRequest
        {
            Action = MisfitsEventAdminAction.Roll,
        });

        RefreshButton.OnPressed += _ => _events.RequestState();
        ApplyIntervalButton.OnPressed += _ => ApplyInterval();
        SetNextButton.OnPressed += _ => SetNextRoll();

        CvarCheck.OnToggled += args =>
        {
            if (_updating)
                return;

            Send(new MisfitsEventAdminActionRequest
            {
                Action = MisfitsEventAdminAction.SetCvarEnabled,
                Enabled = args.Pressed,
            });
        };

        AutoCheck.OnToggled += args =>
        {
            if (_updating)
                return;

            Send(new MisfitsEventAdminActionRequest
            {
                Action = MisfitsEventAdminAction.SetAutoEnabled,
                Enabled = args.Pressed,
            });
        };
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _events.OnStateReceived += OnState;
        _events.RequestState();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _events.OnStateReceived -= OnState;
    }

    private void Send(MisfitsEventAdminActionRequest request)
    {
        _events.SendAction(request);
    }

    private void ApplyInterval()
    {
        if (!float.TryParse(MinIntervalEdit.Text, out var min) || !float.TryParse(MaxIntervalEdit.Text, out var max))
        {
            ResultLabel.Text = "Interval must be a number of seconds.";
            return;
        }

        Send(new MisfitsEventAdminActionRequest
        {
            Action = MisfitsEventAdminAction.SetInterval,
            Min = min,
            Max = max,
        });
    }

    private void SetNextRoll()
    {
        if (!float.TryParse(NextRollEdit.Text, out var seconds))
        {
            ResultLabel.Text = "Next roll must be a number of seconds.";
            return;
        }

        Send(new MisfitsEventAdminActionRequest
        {
            Action = MisfitsEventAdminAction.SetNextRoll,
            Seconds = seconds,
        });
    }

    private void OnState(MisfitsEventsStateEvent msg)
    {
        _updating = true;
        CvarCheck.Pressed = msg.CvarEnabled;
        AutoCheck.Pressed = msg.SchedulerEnabled;
        MinIntervalEdit.Text = ((int) msg.MinInterval).ToString();
        MaxIntervalEdit.Text = ((int) msg.MaxInterval).ToString();
        NextRollEdit.Text = ((int) msg.NextRoll).ToString();
        _updating = false;

        var eligible = msg.Events.Count(info => info.Eligible);
        var cvarState = msg.CvarEnabled ? "on" : "off";

        StatusLabel.Text = msg.SchedulerRunning
            ? $"Scheduler: {(msg.SchedulerEnabled ? "enabled" : "disabled")} (cvar {cvarState}), " +
              $"next roll {msg.NextRoll:0}s, {eligible}/{msg.Events.Count} events eligible."
            : $"Scheduler: not running (cvar {cvarState}), {eligible}/{msg.Events.Count} events eligible.";

        ResultLabel.Text = msg.Message;

        RebuildEvents(msg);
    }

    private void RebuildEvents(MisfitsEventsStateEvent msg)
    {
        EventsContainer.RemoveAllChildren();

        foreach (var info in msg.Events)
        {
            var entry = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 2,
            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            row.AddChild(new Label
            {
                Text = $"{info.Id}  (weight {info.Weight}, {(info.Eligible ? "eligible" : "not eligible")})",
                HorizontalExpand = true,
                Modulate = info.Eligible ? Color.White : Color.Gray,
            });

            var eventId = info.Id;
            var runButton = new Button { Text = "Run", MinWidth = 70 };
            runButton.OnPressed += _ => Send(new MisfitsEventAdminActionRequest
            {
                Action = MisfitsEventAdminAction.Run,
                EventId = eventId,
            });
            row.AddChild(runButton);

            // Jump to where it last spawned, so "far away" is told apart from "nothing".
            if (info.HasSpawn)
            {
                var goButton = new Button { Text = "Go", MinWidth = 70 };
                goButton.OnPressed += _ => Send(new MisfitsEventAdminActionRequest
                {
                    Action = MisfitsEventAdminAction.WarpToLastSpawn,
                    EventId = eventId,
                });
                row.AddChild(goButton);
            }

            entry.AddChild(row);
            entry.AddChild(new Label
            {
                Text = DescribeLastSpawn(info),
                Modulate = Color.LightGray,
            });

            EventsContainer.AddChild(entry);
        }
    }

    private static string DescribeLastSpawn(MisfitsEventInfo info)
    {
        if (!info.HasSpawn)
        {
            return string.IsNullOrEmpty(info.Failure)
                ? "Last run: no spawn recorded this round."
                : $"Last run failed: {info.Failure}.";
        }

        var where = string.IsNullOrEmpty(info.SpawnLocation)
            ? $"({info.SpawnX:0}, {info.SpawnY:0})"
            : $"'{info.SpawnLocation}' ({info.SpawnX:0}, {info.SpawnY:0})";

        return info.SpawnedCount > 0
            ? $"Last run: {info.SpawnedCount} entities at {where}."
            : $"Last run: spawned nothing at {where}.";
    }
}
