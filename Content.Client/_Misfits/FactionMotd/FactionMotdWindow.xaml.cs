using Content.Client.UserInterface.Controls;
using Content.Shared._Misfits.FactionMotd;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Misfits.FactionMotd;

[GenerateTypedNameReferences]
public sealed partial class FactionMotdWindow : FancyWindow
{
    private const int MessageTab = 0;
    private const int EditTab = 1;

    private static readonly Color ErrorColor = Color.FromHex("#d65a4a");

    public event Action? OnRefresh;
    public event Action<string>? OnSave;

    /// <summary>MOTD last received from the server, so a refresh doesn't clobber unsaved edits.</summary>
    private string? _serverText;

    public FactionMotdWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(MessageTab, Loc.GetString("faction-motd-tab-message"));
        Tabs.SetTabTitle(EditTab, Loc.GetString("faction-motd-tab-edit"));
        Tabs.SetTabVisible(EditTab, false);

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        CloseButtonBottom.OnPressed += _ => Close();
        MotdEdit.OnTextChanged += _ => UpdateCounter();
        SaveButton.OnPressed += _ => OnSave?.Invoke(Rope.Collapse(MotdEdit.TextRope));
        ClearButton.OnPressed += _ =>
        {
            MotdEdit.TextRope = new Rope.Leaf(string.Empty);
            UpdateCounter();
            OnSave?.Invoke(string.Empty);
        };

        UpdateCounter();
    }

    public void UpdateState(FactionMotdStateMsg state)
    {
        if (!state.InFaction)
        {
            HeaderLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("faction-motd-no-faction-header")));
            AuthorLabel.Text = string.Empty;
            MessageLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("faction-motd-no-faction")));
            Tabs.SetTabVisible(EditTab, false);
            Tabs.CurrentTab = MessageTab;
            SetStatus(null, false);
            return;
        }

        var header = new FormattedMessage();
        header.PushColor(state.FactionColor);
        header.AddText(Loc.GetString("faction-motd-header", ("faction", state.FactionName)));
        header.Pop();
        HeaderLabel.SetMessage(header);

        AuthorLabel.Text = state.Author != null && state.UpdatedAt is { } updated
            ? Loc.GetString("faction-motd-author",
                ("author", state.Author),
                ("time", updated.ToLocalTime().ToString("yyyy-MM-dd HH:mm")))
            : string.Empty;

        // Leadership writes the MOTD, so render it as plain text (no markup), like the roster oath.
        MessageLabel.SetMessage(FormattedMessage.FromUnformatted(state.Text.Length > 0
            ? state.Text
            : Loc.GetString(state.CanEdit ? "faction-motd-empty-leader" : "faction-motd-empty")));

        Tabs.SetTabVisible(EditTab, state.CanEdit);
        if (!state.CanEdit)
            Tabs.CurrentTab = MessageTab;

        if (_serverText != state.Text)
        {
            _serverText = state.Text;
            MotdEdit.TextRope = new Rope.Leaf(state.Text);
        }

        ClearButton.Disabled = state.Text.Length == 0;
        UpdateCounter();
        SetStatus(state.Status, state.StatusIsError);
    }

    /// <summary>Leadership opening an empty MOTD lands straight on the editor.</summary>
    public void ShowEditorIfEmpty(FactionMotdStateMsg state)
    {
        if (state.CanEdit && state.Text.Length == 0)
            Tabs.CurrentTab = EditTab;
    }

    private void SetStatus(string? status, bool error)
    {
        StatusLabel.Text = status ?? string.Empty;
        StatusLabel.FontColorOverride = error ? ErrorColor : null;
    }

    private void UpdateCounter()
    {
        var length = Rope.Collapse(MotdEdit.TextRope).Length;
        CounterLabel.Text = Loc.GetString("faction-motd-counter",
            ("count", length), ("max", FactionMotdConfig.MaxLength));
        CounterLabel.FontColorOverride = length > FactionMotdConfig.MaxLength ? ErrorColor : null;
        SaveButton.Disabled = length > FactionMotdConfig.MaxLength;
    }
}
