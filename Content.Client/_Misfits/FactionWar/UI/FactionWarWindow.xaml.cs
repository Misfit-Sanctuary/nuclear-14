// #Misfits Refactor - /war panel, rebuilt on the faction roster / recruit window layout.
// Wars tab: every war this round as a card, with Join (was /warjoin) and Ceasefire inline.
// My requests tab: the wars you declared, were declared against, or joined.
// Declare tab: Faction/Group toggle, one target list, reason with a live word count, a plain-English
// preview, then a two-press Declare button. All validation is still done server-side.

using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Misfits.FactionWar;
using Content.Shared._Misfits.RaidRequest;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Utility;

namespace Content.Client._Misfits.FactionWar.UI;

[GenerateTypedNameReferences]
public sealed partial class FactionWarWindow : FancyWindow
{
    public const int WarsTab = 0;
    public const int DeclareTab = 1;
    public const int MyRequestsTab = 2;

    /// <summary>Keep in sync with the server's casus belli check.</summary>
    private const int MinReasonWords = 5;

    private static readonly Color GoodColor = Color.FromHex("#7fc96b");
    private static readonly Color BadColor = Color.FromHex("#d65a4a");
    private static readonly Color WarnColor = Color.FromHex("#d6b85a");
    private static readonly Color MutedColor = Color.FromHex("#8a8a8a");
    private static readonly Color InfoColor = Color.FromHex("#6fa8dc");

    public event Action<WarTargetKind, string, string, string>? OnDeclareWar;
    public event Action<NetUserId>? OnCeasefire;
    public event Action<NetUserId>? OnAcceptCeasefireProposal;
    public event Action<NetUserId>? OnRejectCeasefireProposal;
    public event Action<string, byte>? OnJoinWar;
    public event Action? OnRefresh;

    private PlayerWarPanelDataEvent? _data;
    private NetUserId? _localUserId;
    private NetEntity? _localEntity;
    private NetUserId? _pendingCeasefireFrom;

    // Join state from the /warjoin data request.
    private readonly HashSet<string> _joinableWarKeys = new();
    private bool _alreadyInWar;

    private WarTargetKind _kind = WarTargetKind.Faction;
    private readonly List<WarTargetInfo> _targetItems = new();
    private bool _declareLocked;
    private bool _confirmPending;

    public FactionWarWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(WarsTab, Loc.GetString("faction-war-tab-wars"));
        Tabs.SetTabTitle(DeclareTab, Loc.GetString("faction-war-tab-declare"));
        Tabs.SetTabTitle(MyRequestsTab, Loc.GetString("faction-war-tab-mine"));

        RaidNoticeLabel.FontColorOverride = WarnColor;

        RulesLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("faction-war-rules")));

        var kindGroup = new ButtonGroup(isNoneSetAllowed: false);
        FactionKindButton.Group = kindGroup;
        GroupKindButton.Group = kindGroup;
        FactionKindButton.Pressed = true;
        FactionKindButton.OnPressed += _ => SetKind(WarTargetKind.Faction);
        GroupKindButton.OnPressed += _ => SetKind(WarTargetKind.Group);

        TargetSelector.OnItemSelected += args =>
        {
            TargetSelector.SelectId(args.Id);
            RefreshDeclareForm();
        };
        CasusBelliEdit.OnTextChanged += _ => RefreshDeclareForm();
        DeclareWarButton.OnPressed += _ => OnDeclarePressed();

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        AcceptCeasefireProposalButton.OnPressed += _ =>
        {
            if (_pendingCeasefireFrom is { } from)
                OnAcceptCeasefireProposal?.Invoke(from);
        };
        RejectCeasefireProposalButton.OnPressed += _ =>
        {
            if (_pendingCeasefireFrom is { } from)
                OnRejectCeasefireProposal?.Invoke(from);
        };

        RefreshDeclareForm();
    }

    public void ShowTab(int tab) => Tabs.CurrentTab = tab;

    #region State

    public void UpdateState(
        PlayerWarPanelDataEvent data,
        NetUserId? localUserId,
        NetEntity? localEntity,
        CeasefireProposalEvent? pendingCeasefire)
    {
        _data = data;
        _localUserId = localUserId;
        _localEntity = localEntity;

        UpdateSummary();
        UpdateCeasefireBanner(pendingCeasefire);
        RebuildWars();

        // Round-start lock and personal cooldown only block declaring, so show them on that tab.
        _declareLocked = data.StatusMessage != null;
        DeclareLockedLabel.Visible = _declareLocked;
        DeclareLockedLabel.Text = data.StatusMessage ?? string.Empty;
        DeclareLockedLabel.FontColorOverride = BadColor;

        FactionKindButton.Disabled = data.FactionTargets.Count == 0;
        GroupKindButton.Disabled = data.GroupTargets.Count == 0;
        if (_kind == WarTargetKind.Faction && data.FactionTargets.Count == 0 && data.GroupTargets.Count > 0)
            _kind = WarTargetKind.Group;
        else if (_kind == WarTargetKind.Group && data.GroupTargets.Count == 0)
            _kind = WarTargetKind.Faction;
        FactionKindButton.Pressed = _kind == WarTargetKind.Faction;
        GroupKindButton.Pressed = _kind == WarTargetKind.Group;

        RebuildTargets();
    }

    public void UpdateJoinState(PlayerWarJoinPanelDataEvent data)
    {
        _joinableWarKeys.Clear();
        foreach (var war in data.AvailableWars)
            _joinableWarKeys.Add(war.WarKey);
        _alreadyInWar = data.AlreadyInWar;

        RebuildWars();
    }

    public void ShowResult(bool success, string message)
    {
        StatusLabel.Visible = !string.IsNullOrWhiteSpace(message);
        StatusLabel.Text = message;
        StatusLabel.FontColorOverride = success ? GoodColor : BadColor;
    }

    private void UpdateSummary()
    {
        if (_data == null)
            return;

        SummaryLabel.Text = string.IsNullOrWhiteSpace(_data.MyCharacterName)
            ? Loc.GetString("faction-war-summary-no-character")
            : _data.MyCharacterName;

        var myWar = FindMyWar();
        if (myWar is { } found)
        {
            SummarySubLabel.Text = Loc.GetString("faction-war-summary-in-war",
                ("side", SideLabel(found.War, found.Side)),
                ("war", WarTitle(found.War)));
            SummarySubLabel.FontColorOverride = BadColor;
        }
        else
        {
            SummarySubLabel.Text = Loc.GetString("faction-war-summary-not-in-war",
                ("count", _data.ActiveWars.Count));
            SummarySubLabel.FontColorOverride = null;
        }
    }

    private void UpdateCeasefireBanner(CeasefireProposalEvent? proposal)
    {
        _pendingCeasefireFrom = proposal?.ProposingPlayer;
        CeasefireBanner.Visible = proposal != null;
        if (proposal != null)
        {
            CeasefireBannerLabel.Text = Loc.GetString("faction-war-ceasefire-incoming",
                ("name", proposal.ProposingPlayerName));
        }
    }

    #endregion

    #region Wars tab

    private void RebuildWars()
    {
        WarList.RemoveAllChildren();
        if (_data == null)
            return;

        Tabs.SetTabTitle(WarsTab, _data.ActiveWars.Count == 0
            ? Loc.GetString("faction-war-tab-wars")
            : Loc.GetString("faction-war-tab-wars-count", ("count", _data.ActiveWars.Count)));

        RebuildMyWars();

        if (_data.ActiveWars.Count == 0)
        {
            WarList.AddChild(new Label
            {
                Text = Loc.GetString("faction-war-no-active-wars"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(4, 2),
            });
            return;
        }

        // Your own war first, then wars you can still join, then the rest.
        var myKey = FindMyWar()?.War.WarKey;
        var wars = _data.ActiveWars
            .OrderByDescending(w => w.WarKey == myKey)
            .ThenByDescending(w => _joinableWarKeys.Contains(w.WarKey))
            .ThenBy(w => w.Phase);

        foreach (var war in wars)
            WarList.AddChild(BuildWarCard(war));
    }

    private void RebuildMyWars()
    {
        MyWarsList.RemoveAllChildren();
        if (_data == null)
            return;

        var mine = _data.ActiveWars.Where(w => MySide(w) != null).ToList();
        Tabs.SetTabTitle(MyRequestsTab, mine.Count == 0
            ? Loc.GetString("faction-war-tab-mine")
            : Loc.GetString("faction-war-tab-mine-count", ("count", mine.Count)));

        if (mine.Count == 0)
        {
            MyWarsList.AddChild(new Label
            {
                Text = Loc.GetString("faction-war-no-my-wars"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(4, 2),
            });
            return;
        }

        foreach (var war in mine)
        {
            var role = _localEntity == war.DeclaredByEntity
                ? Loc.GetString("faction-war-role-declarer")
                : _localEntity == war.DeclaredAgainstEntity
                    ? Loc.GetString("faction-war-role-target")
                    : Loc.GetString("faction-war-role-joined", ("side", SideName(war, MySide(war)!.Value)));

            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 2,
            };
            box.AddChild(new Label { Text = role, StyleClasses = { "LabelKeyText" } });
            box.AddChild(BuildWarCard(war));
            MyWarsList.AddChild(box);
        }
    }

    private Control BuildWarCard(PlayerWarEntry war)
    {
        var panel = new PanelContainer { StyleClasses = { "BackgroundDark" } };
        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 4,
            Margin = new Thickness(6, 4),
        };
        panel.AddChild(body);

        // Title row: "A vs B" and the phase on the right.
        var titleRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        titleRow.AddChild(new Label
        {
            Text = WarTitle(war),
            HorizontalExpand = true,
            ClipText = true,
        });
        var (phaseText, phaseColor) = PhaseInfo(war.Phase);
        titleRow.AddChild(new Label { Text = phaseText, FontColorOverride = phaseColor });
        body.AddChild(titleRow);

        body.AddChild(new Label
        {
            Text = Loc.GetString("faction-war-card-declared",
                ("by", war.DeclaredByCharacterName),
                ("against", war.DeclaredAgainstCharacterName)),
            StyleClasses = { "LabelSubText" },
            ClipText = true,
        });

        var reason = new RichTextLabel { HorizontalExpand = true };
        reason.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[color=#aaaaaa][italic]\"{FormattedMessage.EscapeText(war.Reason)}\"[/italic][/color]"));
        body.AddChild(reason);

        // One column per side, each with its headcount and (when allowed) a Join button.
        var mySide = MySide(war);
        var canJoin = !_alreadyInWar && mySide == null && _joinableWarKeys.Contains(war.WarKey);
        var sides = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };
        sides.AddChild(BuildSideColumn(war, 1, mySide, canJoin));
        sides.AddChild(BuildSideColumn(war, 2, mySide, canJoin));
        body.AddChild(sides);

        // Only the two original characters may propose a ceasefire, and only once the war is live.
        if (war.Phase == WarPhase.Active && IsOriginalParticipant(war) && _localUserId is { } me)
        {
            var other = war.DeclaredByPlayer == me ? war.DeclaredAgainstPlayer : war.DeclaredByPlayer;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new Label
            {
                Text = Loc.GetString("faction-war-ceasefire-hint"),
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });
            var ceasefire = new ConfirmButton
            {
                Text = Loc.GetString("faction-war-ceasefire-button"),
                ConfirmationText = Loc.GetString("faction-war-ceasefire-confirm"),
                MinWidth = 150,
            };
            ceasefire.OnPressed += _ => OnCeasefire?.Invoke(other);
            row.AddChild(ceasefire);
            body.AddChild(row);
        }

        return panel;
    }

    private Control BuildSideColumn(PlayerWarEntry war, byte side, byte? mySide, bool canJoin)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        column.AddChild(new Label
        {
            Text = SideLabel(war, side),
            FontColorOverride = mySide == side ? GoodColor : null,
            ClipText = true,
        });

        var count = war.Participants.Count(p => p.Value == side);
        column.AddChild(new Label
        {
            Text = mySide == side
                ? Loc.GetString("faction-war-side-count-you", ("count", count))
                : Loc.GetString("faction-war-side-count", ("count", count)),
            StyleClasses = { "LabelSubText" },
        });

        if (canJoin)
        {
            var join = new ConfirmButton
            {
                Text = Loc.GetString("faction-war-join-side-button", ("side", SideName(war, side))),
                ConfirmationText = Loc.GetString("faction-war-join-confirm-button"),
                ClipText = true,
                HorizontalExpand = true,
                ToolTip = Loc.GetString("faction-war-join-kos-confirm"),
            };
            join.OnPressed += _ => OnJoinWar?.Invoke(war.WarKey, side);
            column.AddChild(join);
        }

        return column;
    }

    #endregion

    #region Declare tab

    private void SetKind(WarTargetKind kind)
    {
        if (_kind == kind)
            return;

        _kind = kind;
        RebuildTargets();
    }

    private void RebuildTargets()
    {
        _targetItems.Clear();
        TargetSelector.Clear();

        var source = _data == null
            ? new List<WarTargetInfo>()
            : _kind == WarTargetKind.Faction ? _data.FactionTargets : _data.GroupTargets;

        // Keep the list unselected until the player picks, so nobody declares on the first entry by accident.
        TargetSelector.AddItem(Loc.GetString(_kind == WarTargetKind.Faction
            ? "faction-war-select-faction"
            : "faction-war-select-group"), -1);

        foreach (var target in source)
        {
            _targetItems.Add(target);
            TargetSelector.AddItem(target.DisplayName, _targetItems.Count - 1);
        }

        TargetSelector.SelectId(-1);
        RefreshDeclareForm();
    }

    private WarTargetInfo? SelectedTarget()
    {
        var idx = TargetSelector.SelectedId;
        return idx >= 0 && idx < _targetItems.Count ? _targetItems[idx] : null;
    }

    private static int WordCount(string text) =>
        text.Split(' ', StringSplitOptions.RemoveEmptyEntries).Length;

    /// <summary>Recompute the word counter, the preview and whether Declare can be pressed.</summary>
    private void RefreshDeclareForm()
    {
        _confirmPending = false;
        DeclareWarButton.Text = Loc.GetString("faction-war-declare-button");

        var target = SelectedTarget();
        var reason = CasusBelliEdit.Text.Trim();
        var words = WordCount(reason);
        var reasonOk = words >= MinReasonWords;

        ReasonCounterLabel.Text = Loc.GetString("faction-war-reason-counter",
            ("count", words), ("min", MinReasonWords));
        ReasonCounterLabel.FontColorOverride = reasonOk ? GoodColor : MutedColor;

        var editable = !_declareLocked;
        TargetSelector.Disabled = !editable || _targetItems.Count == 0;
        CasusBelliEdit.Editable = editable;

        string preview;
        if (_declareLocked)
            preview = Loc.GetString("faction-war-preview-locked");
        else if (_targetItems.Count == 0)
            preview = Loc.GetString("faction-war-preview-no-targets");
        else if (target == null)
            preview = Loc.GetString("faction-war-preview-pick-target");
        else if (!reasonOk)
            preview = Loc.GetString("faction-war-preview-need-reason",
                ("target", FormattedMessage.EscapeText(target.DisplayName)), ("min", MinReasonWords));
        else
            preview = Loc.GetString("faction-war-preview-ready",
                ("target", FormattedMessage.EscapeText(target.DisplayName)),
                ("reason", FormattedMessage.EscapeText(reason)));

        DeclarePreviewLabel.SetMessage(FormattedMessage.FromMarkupPermissive(preview));
        DeclareWarButton.Disabled = !editable || target == null || !reasonOk;
    }

    private void OnDeclarePressed()
    {
        if (DeclareWarButton.Disabled || SelectedTarget() is not { } target)
            return;

        if (!_confirmPending)
        {
            _confirmPending = true;
            DeclareWarButton.Text = Loc.GetString("faction-war-declare-confirm");
            ShowResult(false, Loc.GetString("faction-war-confirm-prompt", ("target", target.DisplayName)));
            return;
        }

        var sideName = string.IsNullOrWhiteSpace(_data?.MyCharacterName)
            ? "Side 1"
            : $"{_data!.MyCharacterName}'s Side";
        OnDeclareWar?.Invoke(target.Kind, target.Id, CasusBelliEdit.Text.Trim(), sideName);
        RefreshDeclareForm();
    }

    #endregion

    #region Helpers

    private (PlayerWarEntry War, byte Side)? FindMyWar()
    {
        if (_data == null)
            return null;

        foreach (var war in _data.ActiveWars)
        {
            if (MySide(war) is { } side)
                return (war, side);
        }

        return null;
    }

    private byte? MySide(PlayerWarEntry war)
    {
        if (_localEntity is { } me && war.Participants.TryGetValue(me, out var side))
            return side;
        return null;
    }

    private bool IsOriginalParticipant(PlayerWarEntry war)
    {
        return _localEntity is { } me
               && (war.DeclaredByEntity == me || war.DeclaredAgainstEntity == me);
    }

    private static string SideName(PlayerWarEntry war, byte side) => side == 1 ? war.SideName1 : war.SideName2;

    /// <summary>"Side name (Faction)" when the side auto-enlists a faction, otherwise just the side name.</summary>
    private static string SideLabel(PlayerWarEntry war, byte side)
    {
        var name = SideName(war, side);
        var faction = side == 1 ? war.Side1FactionId : war.Side2FactionId;
        return string.IsNullOrEmpty(faction)
            ? name
            : $"{name} ({RaidRequestConfig.FactionDisplayName(faction)})";
    }

    private static string WarTitle(PlayerWarEntry war) => $"{SideLabel(war, 1)}  vs  {SideLabel(war, 2)}";

    private static (string Text, Color Color) PhaseInfo(WarPhase phase) => phase switch
    {
        WarPhase.Pending => (Loc.GetString("faction-war-phase-pending"), WarnColor),
        WarPhase.Review => (Loc.GetString("faction-war-phase-review"), InfoColor),
        _ => (Loc.GetString("faction-war-phase-active"), BadColor),
    };

    #endregion
}
