[GenerateTypedNameReferences]
public sealed partial class MotdWindow : FancyWindow
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;
    [Dependency] private readonly ILocalizationManager _loc = default!;
    [Dependency] private readonly IClientAdminManager _adminManager = default!;

    private bool _editorVisible;
    private string? _appliedText;
    private string[] _appliedImages = Array.Empty<string>();
    private readonly List<PollRow> _pollRows = new();

    /// Whether the local player may edit the Message of the Day. Checks after every edits.
    public bool CanEdit => _adminManager.HasFlag(AdminFlags.Admin);

    public event Action<int>? OnVote;

    public event Action<MotdEditMessage>? OnEdit;

    public MotdWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Title = _loc.GetString("motd-ui-title");
        PollHint.Text = _loc.GetString("motd-ui-poll-hint");

        EditPanel.Visible = false;
        EditHeader.Text = _loc.GetString("motd-ui-edit-header");
        EditTextLabel.Text = _loc.GetString("motd-ui-edit-text");
        EditImagesLabel.Text = _loc.GetString("motd-ui-edit-images");
        EditQuestionLabel.Text = _loc.GetString("motd-ui-edit-question");
        EditOptionsLabel.Text = _loc.GetString("motd-ui-edit-options");
        EditHint.Text = _loc.GetString("motd-ui-edit-hint");
        SaveButton.Text = _loc.GetString("motd-ui-edit-save");
        ClearPollButton.Text = _loc.GetString("motd-ui-edit-clear-poll");
        EditToggleButton.Text = _loc.GetString("motd-ui-edit-toggle");
        RefreshPermissions();

        EditToggleButton.OnPressed += _ => SetEditorVisible(!_editorVisible);
        SaveButton.OnPressed += OnSavePressed;
        ClearPollButton.OnPressed += OnClearPollPressed;
    }

    /// Shows the editor above the message, then asks for value to avoid stale.
    public void ShowEditor()
    {
        if (!CanEdit)
            return;

        SetEditorVisible(true);
    }

    private void SetEditorVisible(bool visible)
    {
        if (visible && !CanEdit)
            return;

        _editorVisible = visible;
        EditPanel.Visible = visible;
        EditToggleButton.Text = _loc.GetString(visible ? "motd-ui-edit-toggle-close" : "motd-ui-edit-toggle");

        if (visible)
            OnEdit?.Invoke(new MotdEditMessage { Action = MotdEditAction.RequestState });
    }

    public void RefreshPermissions()
    {
        EditToggleButton.Visible = CanEdit;
        if (!CanEdit)
            SetEditorVisible(false);
    }

    public void Apply(MotdUpdateMessage message)
    {
        // A new tally carries the same message and pictures, so only the parts that actually changed are rebuilt.
        if (!string.Equals(_appliedText, message.Text, StringComparison.Ordinal))
        {
            _appliedText = message.Text;

            var text = new FormattedMessage();
            if (string.IsNullOrWhiteSpace(message.Text))
                text.AddText(_loc.GetString("motd-ui-no-message"));
            else
                text.AddMarkupPermissive(message.Text);

            MotdText.SetMessage(text);
        }

        if (!_appliedImages.SequenceEqual(message.Images))
        {
            _appliedImages = message.Images;
            UpdateImages(message.Images);
        }

        UpdatePoll(message);

        // Only prefill on updates the server sent because the window should be (re)opened, such as answering a save or a state request. Vote tallies arrive without that flag, so any typing is left alone.
        if (message.Open)
            PrefillEditor(message);
    }

    private void PrefillEditor(MotdUpdateMessage message)
    {
        EditText.TextRope = new Rope.Leaf(message.Text);
        EditImages.Text = string.Join("; ", message.Images);
        EditQuestion.Text = message.HasPoll ? message.Question : string.Empty;
        EditOptions.Text = message.HasPoll ? string.Join(" | ", message.Options) : string.Empty;
    }

    private void OnSavePressed(BaseButton.ButtonEventArgs args)
    {
        OnEdit?.Invoke(new MotdEditMessage
        {
            Action = MotdEditAction.Save,
            Text = Rope.Collapse(EditText.TextRope),
            Images = EditImages.Text.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries),
            Question = EditQuestion.Text,
            Options = EditOptions.Text.Split('|', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries),
        });
    }

    private void OnClearPollPressed(BaseButton.ButtonEventArgs args)
    {
        OnEdit?.Invoke(new MotdEditMessage { Action = MotdEditAction.ClearPoll });
    }

    private void UpdateImages(string[] images)
    {
        ImagesContainer.RemoveAllChildren();

        foreach (var path in images)
        {
            if (!_resourceCache.TryGetResource<TextureResource>(new ResPath(path), out var texture))
                continue;

            ImagesContainer.AddChild(new TextureRect
            {
                Texture = texture.Texture,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                MinSize = new System.Numerics.Vector2(0, 160),
                HorizontalExpand = true,
            });
        }

        ImagesContainer.Visible = ImagesContainer.ChildCount > 0;
    }

    private void UpdatePoll(MotdUpdateMessage message)
    {
        PollPanel.Visible = message.HasPoll;
        if (!message.HasPoll)
        {
            ClearPollRows();
            return;
        }

        PollQuestion.Text = _loc.GetString("motd-ui-poll-question", ("question", message.Question));

        if (_pollRows.Count != message.Options.Length)
        {
            ClearPollRows();

            for (var i = 0; i < message.Options.Length; i++)
            {
                var row = new PollRow(i + 1, _loc, OnVotePressed);
                PollOptions.AddChild(row.Root);
                _pollRows.Add(row);
            }
        }

        for (var i = 0; i < _pollRows.Count; i++)
        {
            var votes = i < message.Votes.Length ? message.Votes[i] : 0;
            _pollRows[i].Update(message.Options[i], votes, message.TotalVotes, message.YourVote == i + 1);
        }

        PollTotal.Text = _loc.GetString("motd-ui-poll-total", ("total", message.TotalVotes));
    }

    private void ClearPollRows()
    {
        if (_pollRows.Count == 0)
            return;

        PollOptions.RemoveAllChildren();
        _pollRows.Clear();
    }

    private void OnVotePressed(int option)
    {
        OnVote?.Invoke(option);
    }

    /// One option of the poll, kept alive between tallies so a vote only changes its text and its bar.
    private sealed class PollRow
    {
        public readonly BoxContainer Root;

        private readonly int _number;
        private readonly ILocalizationManager _loc;
        private readonly Button _button;
        private readonly ProgressBar _bar;
        private readonly Label _count;

        public PollRow(int number, ILocalizationManager loc, Action<int> onVote)
        {
            _number = number;
            _loc = loc;

            Root = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                HorizontalExpand = true,
            };

            _button = new Button { HorizontalExpand = true };
            _button.OnPressed += _ => onVote(number);
            Root.AddChild(_button);

            _bar = new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 100f,
                MinWidth = 110,
            };
            Root.AddChild(_bar);

            _count = new Label
            {
                MinWidth = 90,
                HorizontalAlignment = HAlignment.Right,
            };
            Root.AddChild(_count);
        }

        public void Update(string option, int votes, int total, bool yours)
        {
            var percent = total == 0 ? 0 : (int) Math.Round(votes * 100.0 / total);

            var label = _loc.GetString("motd-ui-poll-option", ("number", _number), ("option", option));
            if (yours)
                label += " " + _loc.GetString("motd-ui-poll-yours");

            _button.Text = label;
            _bar.Value = percent;
            _count.Text = _loc.GetString("motd-ui-poll-votes", ("percent", percent), ("votes", votes));
        }
    }
}

/// Keeps the Message of the Day window in sync with the server and forwards votes and edits.
[UsedImplicitly]
public sealed class MotdUIController : UIController
{
    [Dependency] private readonly INetManager _netManager = default!;
    [Dependency] private readonly IClientAdminManager _adminManager = default!;

    private MotdWindow? _window;

    public override void Initialize()
    {
        base.Initialize();

        _netManager.RegisterNetMessage<MotdUpdateMessage>(OnMotdUpdate);
        _netManager.RegisterNetMessage<MotdVoteMessage>();
        _netManager.RegisterNetMessage<MotdEditMessage>();

        _adminManager.AdminStatusUpdated += OnAdminStatusUpdated;
    }

    /// Opens the window with the editor showing. Also used by the admin menu.
    public void OpenEditor()
    {
        var window = EnsureWindow();
        if (!window.CanEdit)
            return;

        window.OpenCentered();
        window.ShowEditor();
    }

    /// Re-checks whether the local player may edit, so a de-admin closes the editor of an open window.
    private void OnAdminStatusUpdated()
    {
        if (_window is { Disposed: false })
            _window.RefreshPermissions();
    }

    private MotdWindow EnsureWindow()
    {
        if (_window == null || _window.Disposed)
        {
            _window = UIManager.CreateWindow<MotdWindow>();
            _window.OnVote += OnVote;
            _window.OnEdit += OnEdit;
        }

        return _window;
    }

    private void OnMotdUpdate(MotdUpdateMessage message)
    {
        if (message.Open)
        {
            var window = EnsureWindow();
            window.Apply(message);
            window.OpenCentered();
            return;
        }

        // Updates the server sends without asking for the window to open, such as new vote tallies, should only be visible to players who are already looking at it.
        if (_window is { Disposed: false, IsOpen: true })
            _window.Apply(message);
    }

    private void OnVote(int option)
    {
        _netManager.ClientSendMessage(new MotdVoteMessage { Option = option });
    }

    private void OnEdit(MotdEditMessage message)
    {
        _netManager.ClientSendMessage(message);
    }
}
